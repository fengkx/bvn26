"""Compile retained display-only frame scripts for the native timeline scheduler."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

from compile_ko import compile_body

ROOT = Path(__file__).resolve().parents[2]


def build(directory: Path) -> None:
    timeline = json.loads((directory / "timeline.json").read_text())
    source = timeline["source_swf"]
    digest = hashlib.sha256((ROOT / source["path"]).read_bytes()).hexdigest()
    bundle = json.loads((ROOT / "scripts/main.json").read_text())
    assert digest == source["sha256"] == bundle["swf_sha256"]
    symbols = {timeline["sprite_id"]} | {
        item["character_id"] for item in timeline["definitions"]
        if item["type"] == "DefineSpriteTag"
    }
    events = []
    code = ["# Generated by tools/importer/compile_display_timeline.py; do not edit.",
            "extends RefCounted", "var adapter: RefCounted", ""]
    for record in bundle["scripts"]:
        location = re.match(r"DefineSprite_(\d+)/", record["path"])
        if not location or int(location[1]) not in symbols:
            continue
        frame = re.fullmatch(r"DefineSprite_(\d+)/frame_(\d+)/DoAction.as", record["path"])
        if not frame or record["source"].strip() != "stop();":
            raise ValueError("Unaudited display-only script: " + record["path"])
        method = f"event_{len(events)}"
        code.append(compile_body(method, record["source"]))
        events.append({"kind": "frame", "sprite_id": int(frame[1]), "frame": int(frame[2]),
                       "method": method, "path": record["path"],
                       "sha256": hashlib.sha256(record["source"].encode()).hexdigest()})
    (directory / "controller.gd").write_text("\n".join(code))
    (directory / "controller.json").write_text(json.dumps(
        {"source_swf": source, "events": events}, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    build(parser.parse_args().directory)
