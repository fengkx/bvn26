"""Compile Sprite 2's hit-packet state transfer, retaining its target intent.

Collision detection is already performed by the caller. This emits the source
field writes and target selection, not damage, hit effects or target DoAction.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

from compile_ai_body import compile_function
from compile_ai_predicates import ROOT, FUNCTION, PRELUDE

HEADER = '''
var packet: Dictionary
var target: Dictionary

func transfer(hit: Dictionary, guard: bool) -> Dictionary:
\tpacket = hit
\ttarget = {}
\tif guard:
\t\ttransfer_guard()
\telse:
\t\ttransfer_normal()
\treturn target

func checkHit() -> bool:
\treturn not packet.is_empty()

func packet_field(key: String) -> Variant:
\treturn packet.get(key)

func _target(label: String, play: bool) -> void:
\ttarget = {"label": label, "play": play}
'''


def compile_transfer(bundle: dict) -> tuple[str, dict]:
    if hashlib.sha256((ROOT / bundle['game_file']).read_bytes()).hexdigest() != bundle['swf_sha256']:
        raise ValueError('Retained hit source hash mismatch')
    # Receiver symbol ids are SWF-local.  Select the retained source by its
    # complete function contract instead of assuming Sprite_2 (Lee uses 5).
    required = {'gameRunning', 'beida', 'fangyu', 'checkHit', 'getHitObj', 'getStgHitObj'}
    candidates = []
    for script in bundle['scripts']:
        if not re.fullmatch(r'DefineSprite_\d+/frame_1/DoAction.as', script['path']):
            continue
        functions = {m[1] for m in FUNCTION.finditer(script['source'].replace('\r\n', '\n'))}
        if required.issubset(functions):
            candidates.append(script)
    if len(candidates) > 1:
        # A bundle can retain another form's identical receiver source.  The
        # base timeline is authoritative for which symbol is actually placed.
        fighter_stem = Path(bundle['game_file']).stem
        timeline_path = ROOT / f"data/slices/{fighter_stem}-base.timeline.json"
        placed = set()
        if timeline_path.is_file():
            timeline = json.loads(timeline_path.read_text())
            placed = {str(p.get('character_id')) for frame in timeline.get('frames', [])
                      for p in frame.get('display_list', [])}
        candidates = [s for s in candidates if re.match(r'DefineSprite_(\d+)/', s['path'])[1] in placed]
    if len(candidates) != 1:
        raise ValueError(f'Expected one source receiver implementation for base timeline, found {len(candidates)}')
    receiver_script = candidates[0]
    path = receiver_script['path']
    source = receiver_script['source']
    functions = {m[1]: (m[2], m[3]) for m in FUNCTION.finditer(source.replace('\r\n', '\n'))}
    text = '# Generated by tools/importer/compile_ai_hit_state.py; do not edit.\n' + PRELUDE + HEADER
    guard_source = functions['checkHit'][1].split('   var _loc3_ = getHitObj(', 1)
    if len(guard_source) != 2 or guard_source[0].count('return null;') != 2:
        raise ValueError('Unsupported hit eligibility guard structure')
    guards = guard_source[0].replace('gameRunning()', 'running').replace('_parent.', '')
    # This extracted predicate answers whether lookup is reached, not which
    # hit object checkHit returns. Its early null results therefore mean false.
    guards = guards.replace('return null;', 'return false;')
    text += compile_function('allows_hit', 'running', guards + '   return true;\n')
    for source_name, native_name in [('beida', 'transfer_normal'), ('fangyu', 'transfer_guard')]:
        params, body = functions[source_name]
        body = body.replace('_parent.', '')
        body = re.sub(r'_loc2_\.(pw|zl|yup|hitx|hdtime|htype)\b', r'packet_field("\1")', body)
        native = compile_function(native_name, params, body, frozenset(('packet_field', 'checkHit')))
        text += native.replace('adapter.goto_label(', '_target(')
    return text, {'path': path, 'functions': ['beida', 'fangyu', 'checkHit guards'],
                  'source_swf': bundle['game_file'], 'swf_sha256': bundle['swf_sha256'],
                  'source_sha256': hashlib.sha256(source.encode()).hexdigest(),
                  'scope': 'Packet state writes and target intent only; no collision, damage or frame execution.'}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--fighter', required=True)
    args = parser.parse_args()
    bundle = json.loads((ROOT / f'scripts/fighter/{args.fighter}.json').read_text())
    native, metadata = compile_transfer(bundle)
    directory = ROOT / f'godot/generated/fighters/{args.fighter}'
    (directory / 'ai_hit_state.gd').write_text(native)
    (directory / 'ai_hit_state.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'fighter': args.fighter, 'functions': 2}))


if __name__ == '__main__':
    main()
