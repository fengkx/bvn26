#!/usr/bin/env python3
"""Compile native-verified missing-field callbacks for the Godot regression."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/importer'))
from compile_ai_controller import compile_body
from compile_ai_predicates import PRELUDE, AVM1_RELATIONAL
from compile_ai_context import writes


def build() -> str:
    code = '# Generated by tools/probes/build_missing_form_fields_fixture.py; do not edit.\n'
    code += PRELUDE + AVM1_RELATIONAL + '''
var adapter: RefCounted

# Match the explicitly controlled native branch probe inputs.
func gameRunning() -> bool:
\treturn true

func airhit() -> bool:
\treturn true

func airMagichit() -> bool:
\treturn false
'''
    for name, sprite, frame, character, depth, field in [
            ('Sasuke', 1019, 135, 16, 36, 'khitn'), ('yihu', 1180, 143, 651, 32, 'nn')]:
        bundle = json.loads((ROOT / f'scripts/fighter/{name}.json').read_text())
        if hashlib.sha256((ROOT / bundle['game_file']).read_bytes()).hexdigest() != bundle['swf_sha256']:
            raise ValueError('Missing-field fixture source hash mismatch')
        path = f'DefineSprite_{sprite}/frame_{frame}/PlaceObject2_{character}_{depth}/CLIPACTIONRECORD onClipEvent(enterFrame).as'
        source = next(row['source'] for row in bundle['scripts'] if row['path'] == path)
        code += f'\n# {bundle["game_file"]}:{path}\n# Source SHA-256: {hashlib.sha256(source.encode()).hexdigest()}\n'
        body = source[source.index('{') + 1:source.rindex('}')]
        code += compile_body(name.lower() + '_callback', '', body, scope_fields={field}, avm1_comparisons=True)
        if name == 'Sasuke':
            action_path = 'DefineSprite_1019/frame_128/DoAction.as'
            action = next(row['source'] for row in bundle['scripts'] if row['path'] == action_path)
            code += '\nconst KHIT_WRITES = ' + json.dumps(writes(action, action_path,
                controller_scope_fields={'khitn'}), ensure_ascii=False) + '\n'
    return code


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(build())
